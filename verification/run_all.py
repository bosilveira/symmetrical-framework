"""Run every registered check and report.

Usage:
    python verification/run_all.py                 # run all checks
    python verification/run_all.py --only F01 D02  # run selected IDs
    python verification/run_all.py --write-ledger  # also (re)generate 00-meta/CLAIMS.md

Exit code is non-zero if any check fails (used by the CI workflow).
"""
import argparse
import json
import os
import sys
import time
import traceback

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import checks  # noqa: E402


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--only', nargs='*', default=None)
    ap.add_argument('--write-ledger', action='store_true')
    args = ap.parse_args()

    results = []
    failed = 0
    for c in checks.CHECKS:
        if args.only and c['id'] not in args.only:
            continue
        t0 = time.time()
        try:
            good, detail = c['fn']()
        except Exception as exc:  # a crashing check counts as a failure
            good, detail = False, 'EXCEPTION: %r\n%s' % (exc, traceback.format_exc(limit=2))
        dt = time.time() - t0
        results.append(dict(id=c['id'], status=c['status'], statement=c['statement'], where=c['where'],
                            passed=bool(good), detail=str(detail), seconds=round(dt, 1)))
        failed += 0 if good else 1
        print('%-4s %-4s %5.1fs  %s' % (c['id'], 'PASS' if good else 'FAIL', dt, detail if not good else ''))
        sys.stdout.flush()

    with open(os.path.join(HERE, 'results.json'), 'w') as fh:
        json.dump(results, fh, indent=2)

    print('\n%d checks, %d passed, %d failed' % (len(results), len(results) - failed, failed))

    if args.write_ledger:
        root = os.path.dirname(HERE)
        out = os.path.join(root, '00-meta', 'CLAIMS.md')
        os.makedirs(os.path.dirname(out), exist_ok=True)
        lines = ['# Claims ledger (generated by `verification/run_all.py --write-ledger`; do not edit by hand)', '',
                 'Status labels: **[T]** proved in the text; **[V]** verified by `verification/checks.py`; '
                 '**[K]** known result (not re-checked); **[I]** interpretation.  '
                 'The last column is the result of the most recent run of the check.', '',
                 '| ID | Status | Statement | Where | Check |', '|---|---|---|---|---|']
        for r in sorted(results, key=lambda r: r['id']):
            lines.append('| %s | [%s] | %s | %s | %s |' % (r['id'], r['status'], r['statement'].replace('|', '\\|'), r['where'],
                                                           'pass' if r['passed'] else '**FAIL**'))
        lines += ['', 'Claims labelled [T], [K] or [I] live in the paper text; their status is recorded in the paper ledger '
                  '(foundational paper, section 7) and in `literature/BIBLIOGRAPHY.md`.']
        with open(out, 'w') as fh:
            fh.write('\n'.join(lines) + '\n')
        print('wrote', out)

    sys.exit(1 if failed else 0)


if __name__ == '__main__':
    main()
